/// Serialized rejection value for Tauri commands; the frontend switches on
/// `kind` to decide between clearing tokens and retrying.
#[derive(Debug, Serialize)]
#[serde(tag = "kind", content = "message", rename_all = "snake_case")]
pub enum CommandError {
    NotConfigured(String),
    Network(String),
    BadResponse(String),
    InvalidGrant(String),
    InvalidClient(String),
}

#[tauri::command]
pub fn oauth_redirect_uri() -> &'static str {
    REDIRECT_URI
}

#[tauri::command]
pub async fn oauth_begin(
    service: String,
    state: String,
    code_verifier: Option<String>,
    states: TauriState<'_, OAuthStateStore>,
) -> Result<(), String> {
    if service != "twitch" && service != "youtube" {
        return Err("unsupported OAuth service".to_string());
    }
    if state.len() < 16 {
        return Err("state is too short".to_string());
    }
    if !CALLBACK_SERVER_READY.load(Ordering::Acquire) {
        return Err("Login server is not running. Please restart StreamTTS and try again.".to_string());
    }

    let mut map = states.write().await;
    let now = now_secs();
    map.retain(|_, entry| now.saturating_sub(entry.created_at) < OAUTH_STATE_EXPIRY_SECS);
    map.insert(state, OAuthStateEntry {
        service,
        created_at: now,
        code_verifier,
    });
    Ok(())
}

/// Single-use state consumption: removes the entry and requires it to be
/// unexpired. Callers are responsible for checking `service`.
async fn consume_state(states: &OAuthStateStore, state: &str) -> Option<OAuthStateEntry> {
    let mut map = states.write().await;
    map.remove(state).filter(|entry| {
        now_secs().saturating_sub(entry.created_at) <= OAUTH_STATE_EXPIRY_SECS
    })
}

#[derive(Clone)]
struct OAuthServerState {
    sender: broadcast::Sender<OAuthCallback>,
    alert_sender: broadcast::Sender<AlertPayload>,
    rate_limiter: Arc<RwLock<RateLimiter>>,
    oauth_states: OAuthStateStore,
    twitch_eventsub_secret: String,
    youtube_hub_secret: String,
}

#[derive(Clone)]
struct RateLimiter {
    requests: HashMap<String, Vec<u64>>,
}

impl RateLimiter {
    fn new() -> Self {
        RateLimiter {
            requests: HashMap::new(),
        }
    }

    fn check_and_record(&mut self, client_ip: &str) -> bool {
        let now = now_secs();

        let window_start = now.saturating_sub(60);

        let entry = self.requests.entry(client_ip.to_string()).or_insert_with(Vec::new);
        entry.retain(|&timestamp| timestamp > window_start);

        if entry.len() >= MAX_REQUESTS_PER_MINUTE as usize {
            return false;
        }

        entry.push(now);
        true
    }
}

/// Constant-time equality over hex strings of equal length.
fn constant_time_eq(a: &str, b: &str) -> bool {
    if a.len() != b.len() {
        return false;
    }
    a.bytes().zip(b.bytes()).fold(0u8, |acc, (x, y)| acc | (x ^ y)) == 0
}

/// Reject deliveries whose timestamp drifts beyond the replay window.
fn eventsub_timestamp_fresh(timestamp: &str) -> bool {
    match chrono::DateTime::parse_from_rfc3339(timestamp) {
        Ok(parsed) => (now_secs() as i64 - parsed.timestamp()).abs() <= EVENTSUB_MAX_SKEW_SECS,
        Err(_) => false,
    }
}

/// Verify Twitch EventSub message signature against the per-install secret.
fn verify_twitch_signature(headers: &HeaderMap, body: &str, secret: &str) -> bool {
    let message_id = headers.get("Twitch-Eventsub-Message-Id")
        .and_then(|h| h.to_str().ok())
        .unwrap_or("");
    let timestamp = headers.get("Twitch-Eventsub-Message-Timestamp")
        .and_then(|h| h.to_str().ok())
        .unwrap_or("");
    let signature = headers.get("Twitch-Eventsub-Message-Signature")
        .and_then(|h| h.to_str().ok())
        .unwrap_or("");

    if message_id.is_empty() || timestamp.is_empty() || signature.is_empty() {
        return false;
    }

    if !eventsub_timestamp_fresh(timestamp) {
        log::warn!("Twitch EventSub delivery outside timestamp window - rejecting possible replay");
        return false;
    }

    let message = format!("{}{}{}", message_id, timestamp, body);

    let mut mac = match HmacSha256::new_from_slice(secret.as_bytes()) {
        Ok(mac) => mac,
        Err(_) => return false,
    };

    mac.update(message.as_bytes());
    let expected = format!("sha256={}", hex::encode(mac.finalize().into_bytes()));

    constant_time_eq(&expected, signature)
}

/// Verify a PubSubHubbub/Websub delivery signed with the per-install hub
/// secret. Accepts both sha1 (PubSubHubbub 0.4) and sha256 (Websub) forms.
fn verify_hub_signature(headers: &HeaderMap, body: &str, secret: &str) -> bool {
    let signature = headers.get("X-Hub-Signature")
        .and_then(|h| h.to_str().ok())
        .unwrap_or("");
    if signature.is_empty() {
        return false;
    }

    let Some((algo, sig)) = signature.split_once('=') else {
        return false;
    };

    let computed = match algo {
        "sha1" => {
            let Ok(mut mac) = HmacSha1::new_from_slice(secret.as_bytes()) else { return false };
            mac.update(body.as_bytes());
            hex::encode(mac.finalize().into_bytes())
        }
        "sha256" => {
            let Ok(mut mac) = HmacSha256::new_from_slice(secret.as_bytes()) else { return false };
            mac.update(body.as_bytes());
            hex::encode(mac.finalize().into_bytes())
        }
        _ => return false,
    };

    constant_time_eq(&computed, sig)
}

/// Check if origin is allowed
/// Allows known development origins OR requests without Origin header (Tauri local requests)
fn is_allowed_origin(headers: &HeaderMap) -> bool {
    let allowed = [
        "http://localhost:3000",
        "http://localhost:8080",
        "http://localhost:5173",
    ];

    if let Some(origin) = headers.get(ORIGIN).and_then(|h| h.to_str().ok()) {
        return allowed.iter().any(|&a| a == origin);
    }

    // Check for Tauri-specific header (webview local request)
    // This is a defensive check - Tauri requests typically don't send Origin
    if let Some(host) = headers.get("host").and_then(|h| h.to_str().ok()) {
        if host.starts_with("127.0.0.1:") || host.starts_with("localhost:") {
            return true;
        }
    }

    // Reject requests without origin from non-local hosts
    // This prevents CSRF from external sites
    false
}

pub async fn start_oauth_server(
    sender: broadcast::Sender<OAuthCallback>,
    alert_sender: broadcast::Sender<AlertPayload>,
    oauth_states: OAuthStateStore,
    twitch_eventsub_secret: String,
    youtube_hub_secret: String,
) -> anyhow::Result<()> {
    if !is_youtube_auth_configured() {
        log::warn!("YOUTUBE_CLIENT_SECRET not set. YouTube OAuth will return configuration errors.");
    }

    let state = Arc::new(OAuthServerState {
        sender,
        alert_sender,
        rate_limiter: Arc::new(RwLock::new(RateLimiter::new())),
        oauth_states,
        twitch_eventsub_secret,
        youtube_hub_secret,
    });
    let app = Router::new()
        .route("/callback", get(handle_callback))
        .route("/auth-complete", post(handle_auth_complete))
        .route("/auth-exchange", post(handle_auth_exchange))
        .route("/twitch-alerts", post(handle_twitch_alerts))
        .route("/youtube-alerts", get(handle_youtube_challenge).post(handle_youtube_alerts))
        .with_state(state);

    let addr = SocketAddr::from(([127, 0, 0, 1], 3000));
    let listener = TcpListener::bind(addr).await?;
    log::info!("OAuth server listening on {}", addr);
    CALLBACK_SERVER_READY.store(true, Ordering::Release);

    axum::serve(listener, app).await?;
    Ok(())
}

async fn check_rate_limit(state: &Arc<OAuthServerState>, client_ip: &str) -> bool {
    let mut limiter = state.rate_limiter.write().await;
    limiter.check_and_record(client_ip)
}

