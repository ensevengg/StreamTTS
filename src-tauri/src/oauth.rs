const REDIRECT_URI: &str = "http://localhost:3000/callback";
const MAX_REQUESTS_PER_MINUTE: u32 = 30;
/// Timestamp skew window for Twitch EventSub signatures; deliveries outside
/// it are treated as replays.
const EVENTSUB_MAX_SKEW_SECS: i64 = 600;

/// Set once the loopback server has successfully bound its port. Auth flows
/// refuse to start (and send the user to the browser) while it is down.
static CALLBACK_SERVER_READY: AtomicBool = AtomicBool::new(false);

/// A state value generated by the webview and registered through the
/// `oauth_begin` command before the provider flow starts. The loopback
/// callback server consumes each entry exactly once. `code_verifier` carries
/// the PKCE verifier for authorization-code flows; it never travels through
/// the browser.
#[derive(Debug, Clone)]
pub struct OAuthStateEntry {
    pub service: String,
    pub created_at: u64,
    pub code_verifier: Option<String>,
}

pub type OAuthStateStore = Arc<RwLock<HashMap<String, OAuthStateEntry>>>;

const OAUTH_STATE_EXPIRY_SECS: u64 = 600;

fn now_secs() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}

